/// Pinned rootfs: the suite plus a pointer to the solved package manifest that
/// content-pins every package (name → version → sha256) — the reproducibility
/// guarantee.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct RootfsPin {
    /// The [distro layer](crate::distro::DistroLayer) the suite resolved to, by stem.
    ///
    /// Recorded although the suite determines it, because the solved manifest beside
    /// the lock was resolved against that distribution's archive. A config change could
    /// move the suite to another layer. Every pin here would then describe the wrong
    /// archive, and the drift check names that rather than building from them.
    pub distro: String,
    /// The suite, as the distribution's archive names it.
    pub suite: String,
    /// Filename of the content-pinned solved package manifest, committed beside
    /// the lock (`recipes/<manifest>`). Deserialization enforces a bare filename.
    #[serde(deserialize_with = "de_bare_filename")]
    pub manifest: String,
    /// sha256 of that committed manifest file, pinning the manifest itself so a
    /// committed-manifest that drifts from the lock is caught. `None` until
    /// the manifest is committed beside the lock — the manifest-as-input wiring
    /// sets it; a bare `update` before any build leaves it unset. Deserialization
    /// enforces the 64-lowercase-hex shape.
    #[serde(
        default,
        skip_serializing_if = "Option::is_none",
        deserialize_with = "de_opt_sha256"
    )]
    pub manifest_sha256: Option<String>,
    /// The rootfs build's `SOURCE_DATE_EPOCH`, in Unix seconds: the time of the
    /// `update` that last moved one of this lock's pins.
    ///
    /// Every time the rootfs stage stamps derives from it. It caps each rootfs
    /// member's mtime, and the target-side customize step runs under it, so
    /// `mkinitramfs` and `useradd` write it rather than the wall clock. The image's
    /// filesystem takes its format time from the newest mtime, so the image inherits
    /// it too.
    ///
    /// It lives in the lock rather than being read from a source tree. A board that
    /// installs Debian's kernel compiles nothing, and a build that restores its kernel
    /// from the artifact cache clones no tree to read. The compile stages keep their own
    /// epochs, read from the tree each one builds.
    ///
    /// It changes only when a pin moves ([`Lock::keep_source_date_epoch`]). So it joins
    /// the rootfs cache key without costing a cache hit, and `reproduce` replays it with
    /// the lock.
    pub source_date_epoch: u64,
}

/// Pinned rkbin blobs: the commit of the rkbin repository they are fetched from, and
/// each file as `"<filename>@sha256:<hex>"`.
///
/// The commit says where the bytes come from and the sha256 says what they are. The
/// u-boot stage fetches each named file at `commit` and refuses one whose hash
/// differs, so a re-pushed or tampered upstream cannot change the bootloader. A
/// `--blobs-dir` build reads the files from a local directory instead and is held to
/// the same hashes.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct BlobsPin {
    /// Clone URL the commit was pinned from (the resolved `[rkbin.upstream].git`).
    /// The drift gate compares it against a fresh resolve.
    pub source: String,
    /// The branch `update` resolved the commit from (TOML key `ref`).
    #[serde(rename = "ref")]
    pub reference: String,
    /// The rkbin commit every file below is fetched at. Deserialization enforces the
    /// full-hex-sha shape. `update` keeps it while it still contains every named file,
    /// since rkbin deletes a blob's older versions when it publishes a newer one.
    #[serde(deserialize_with = "de_commit")]
    pub commit: String,
    /// rkbin BL31 blob pin, present iff the BL31 provider is `rkbin`. A `tfa` build
    /// pins its BL31 as [`Lock::tfa`] and serializes without the field.
    /// Deserialization enforces the `"<filename>@sha256:<hex64>"` shape.
    #[serde(
        default,
        skip_serializing_if = "Option::is_none",
        deserialize_with = "de_opt_blob_pin"
    )]
    pub atf: Option<String>,
    /// DDR TPL blob pin, required under either BL31 provider. Shape-enforced like
    /// [`atf`](Self::atf).
    #[serde(deserialize_with = "de_blob_pin")]
    pub tpl: String,
    /// OP-TEE BL32 blob pin, present only when the build has one. Absent on
    /// BL31-only boots (RK3588/RK1), so those locks serialize without the field.
    /// Shape-enforced like [`atf`](Self::atf) when present.
    #[serde(
        default,
        skip_serializing_if = "Option::is_none",
        deserialize_with = "de_opt_blob_pin"
    )]
    pub bl32: Option<String>,
}

/// How a captured snapshot participates in a build.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum SnapshotMode {
    /// Provenance only. Builds use the live mirror.
    Off,
    /// Live mirror first, snapshot fills anything that 404s.
    Fallback,
    /// Build exclusively against the snapshot.
    Pin,
}

impl SnapshotMode {
    /// The mode's lowercase name — matches the serialized TOML form and the
    /// `--snapshot` CLI value, so error messages and the flag agree.
    pub fn as_str(self) -> &'static str {
        match self {
            SnapshotMode::Off => "off",
            SnapshotMode::Fallback => "fallback",
            SnapshotMode::Pin => "pin",
        }
    }
}

/// A captured `snapshot.debian.org` timestamp and its activation mode.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SnapshotPin {
    /// Snapshot timestamp (e.g. `20260628T083000Z`).
    pub timestamp: String,
    /// Whether/how the snapshot is used.
    pub mode: SnapshotMode,
}

